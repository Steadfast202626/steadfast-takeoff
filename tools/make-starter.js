/*
 * Copies data/price-book-starter.csv and data/assemblies-starter.csv into app/js/starter-library.js,
 * because Netlify publishes app/ only. Run after changing either CSV: node tools/make-starter.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

function build() {
  const root = path.join(__dirname, '..');
  const priceBookCsv = fs.readFileSync(path.join(root, 'data', 'price-book-starter.csv'), 'utf8');
  const assembliesCsv = fs.readFileSync(path.join(root, 'data', 'assemblies-starter.csv'), 'utf8');
  return '/* Generated by tools/make-starter.js from data/. Do not edit by hand. */\n' +
    'window.SteadfastStarter = ' + JSON.stringify({ priceBookCsv, assembliesCsv }, null, 1) + ';\n';
}

module.exports = { build };

if (require.main === module) {
  const out = path.join(__dirname, '..', 'app', 'js', 'starter-library.js');
  fs.writeFileSync(out, build());
  console.log('Wrote ' + out);
}
